/**
 * v0.10.3：工坊是**桌面工具**，不做移动端适配。
 *
 * 这里不是「还没适配」，是**决定不适配**。编辑器左侧资源 / 图层面板 280、
 * 右侧信息抽屉 320、底部动作胶囊条 13 个动作，1024 宽时画布只剩 424px；
 * 再往下压，任何一栏都摊不开，只能全部折叠成抽屉，那是另一套产品。
 *
 * 但「不适配」不等于「让它被裁掉」。评审实测（`.impeccable/critique/`）：
 * 375 宽下 `/hlm/maps` 的文档被撑到 561px、多出的 186px 被 `overflow` 吞掉，
 * 既看不到也滚不到；`/hlm/maps/15420/edit` 的顶栏 532px，`保存` 与 `发布`
 * 永久停在屏外 —— 窄屏上这两条路等于不存在。那不是「桌面工具在手机上难看」，
 * 是「桌面工具在手机上坏掉」。
 *
 * 所以给工坊的根容器一个下限宽度：窄屏上整页横向滚动，桌面零影响。
 * 滚一滚虽然笨，但每一个按钮都还能按到。
 *
 * 玩家侧（`/play`、`/play/:slug`）**不吃这条**：它们是手机上玩的，另有一套
 * 自己的竖屏排布（v0.10.0 / v0.10.1 那一串）。
 */
export const WORKSHOP_MIN_WIDTH = 1024;

/**
 * 同上，写成类名。Tailwind 的 JIT 只认字面量，所以这个字符串必须与
 * `WORKSHOP_MIN_WIDTH` 手写一致 —— 改宽度时两处一起改。
 */
export const WORKSHOP_MIN_WIDTH_CLASS = 'min-w-[1024px]';
